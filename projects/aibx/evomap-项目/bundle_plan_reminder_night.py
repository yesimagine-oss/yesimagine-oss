def check_and_notify():
    """检查时间并发送通知"""
    now = datetime.now()
    current_time = now.strftime("%H:%M")
    
    reminders = {
        "22:00": "wake_up",
        "22:30": "work_start",
        "01:00": "midnight_snack",
        "01:30": "continue_work",
        "05:00": "daily_report",
        "05:30": "work_end",
        "06:30": "sleep",
        "14:00": "wake_up_afternoon",
    }
    
    if current_time in reminders:
        show_reminder(reminders[current_time])

